#!/usr/bin/env node
/**
 * Regenerate src/types/supabase.ts from DrFlow-Staging (never production).
 * Usage: npm run supabase:types
 */
import { spawnSync } from "child_process";
import { writeFileSync } from "fs";
import { resolve } from "path";

const STAGING_REF = "gprmsufvhabntbrytwyi";
const PRODUCTION_REF = "nipqdarduknydqptqzup";
const OUT = resolve(process.cwd(), "src/types/supabase.ts");

if (process.env.SUPABASE_PROJECT_ID === PRODUCTION_REF) {
  console.error(`Refusing to generate types from production (${PRODUCTION_REF}).`);
  process.exit(1);
}

const projectId = process.env.SUPABASE_PROJECT_ID || STAGING_REF;
if (projectId === PRODUCTION_REF) {
  console.error(`Refusing to generate types from production (${PRODUCTION_REF}).`);
  process.exit(1);
}

const result = spawnSync(
  "npx",
  ["supabase", "gen", "types", "typescript", "--project-id", projectId, "--schema", "public"],
  { encoding: "utf8", shell: true }
);

if (result.status !== 0) {
  process.stderr.write(result.stderr || result.stdout || "supabase gen types failed\n");
  process.exit(result.status ?? 1);
}

const stdout = result.stdout ?? "";
if (!stdout.includes("export type Database")) {
  console.error("Generated output missing export type Database");
  process.exit(1);
}
if (!stdout.includes("clinic_entitlement_subscriptions")) {
  console.error(
    "Generated types missing clinic_entitlement_subscriptions — apply migrations 121–128 on staging first."
  );
  process.exit(1);
}

const header = `/**
 * Generated by npm run supabase:types from Supabase project ${projectId} (DrFlow-Staging).
 * Do not edit by hand. Re-run the script after schema changes.
 */
`;

writeFileSync(OUT, header + stdout, "utf8");
console.log(`Wrote ${OUT}`);
console.log(`Project: ${projectId} (staging expected: ${STAGING_REF})`);
