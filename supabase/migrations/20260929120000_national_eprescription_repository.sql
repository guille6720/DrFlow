-- National electronic prescription (ReNaPDiS) — repository/CUIR lifecycle (STAGING first).
--
-- Separation of concerns:
--   REFEPS  = professional validation only        -> refeps_professional_status / refeps_validated_at
--   Repository (ReNaPDiS-approved, external)      -> repository_* / cuir
--   Sandbox                                       -> sandbox_reference ONLY (never cuir)
--
-- Additive + idempotent. Existing rows keep national_rx_state = NULL (local prescriptions, unchanged).
-- Legacy columns (refeps_status, refeps_id, cuir_status, cuir_* components, national_rx_status) are untouched.
-- National columns are writable ONLY by service_role (server); browsers cannot set a CUIR.
-- Rollback: supabase/migrations/rollback/20260929120000_national_eprescription_repository.down.sql

-- ---------------------------------------------------------------------------
-- 1. Columns
-- ---------------------------------------------------------------------------
ALTER TABLE public.prescription_drafts
  ADD COLUMN IF NOT EXISTS national_rx_state text,
  ADD COLUMN IF NOT EXISTS national_rx_updated_at timestamptz,
  ADD COLUMN IF NOT EXISTS national_submission_id uuid,
  ADD COLUMN IF NOT EXISTS national_idempotency_key text,
  ADD COLUMN IF NOT EXISTS national_correlation_id text,
  ADD COLUMN IF NOT EXISTS national_attempts integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS repository_provider text,
  ADD COLUMN IF NOT EXISTS repository_mode text,
  ADD COLUMN IF NOT EXISTS repository_prescription_id text,
  ADD COLUMN IF NOT EXISTS provider_request_id text,
  ADD COLUMN IF NOT EXISTS repository_status text,
  ADD COLUMN IF NOT EXISTS repository_submitted_at timestamptz,
  ADD COLUMN IF NOT EXISTS repository_last_checked_at timestamptz,
  ADD COLUMN IF NOT EXISTS repository_error_code text,
  ADD COLUMN IF NOT EXISTS repository_error_message text,
  ADD COLUMN IF NOT EXISTS sandbox_reference text,
  ADD COLUMN IF NOT EXISTS cuir text,
  ADD COLUMN IF NOT EXISTS cuir_received_at timestamptz,
  ADD COLUMN IF NOT EXISTS cuir_verified_at timestamptz,
  ADD COLUMN IF NOT EXISTS refeps_professional_status text,
  ADD COLUMN IF NOT EXISTS refeps_validation_mode text,
  ADD COLUMN IF NOT EXISTS refeps_validated_at timestamptz;

COMMENT ON COLUMN public.prescription_drafts.cuir IS
  'Official CUIR returned by an external ReNaPDiS repository. Never generated by NexClinic. Never sandbox.';
COMMENT ON COLUMN public.prescription_drafts.sandbox_reference IS
  'Sandbox/test reference (SBX-*). NOT a CUIR. Not valid for dispensing.';
COMMENT ON COLUMN public.prescription_drafts.national_rx_state IS
  'National e-Rx lifecycle (NULL = local only). Mirrors src/core/renapdis/national-state-machine.ts.';

-- ---------------------------------------------------------------------------
-- 2. Constraints
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_national_rx_state_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_national_rx_state_check CHECK (
      national_rx_state IS NULL OR national_rx_state IN (
        'issued_local', 'professional_validation_pending', 'professional_validated',
        'professional_validation_failed', 'repository_submission_pending', 'repository_submitted',
        'repository_submission_failed', 'repository_unavailable', 'cuir_assigned',
        'cuir_verification_failed', 'cancelled'
      )
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_national_rx_not_draft_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_national_rx_not_draft_check
      CHECK (national_rx_state IS NULL OR status <> 'draft');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_repository_mode_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_repository_mode_check
      CHECK (repository_mode IS NULL OR repository_mode IN ('sandbox', 'external'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_repository_status_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_repository_status_check
      CHECK (repository_status IS NULL OR repository_status IN ('registered', 'pending', 'rejected', 'cancelled'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_refeps_professional_status_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_refeps_professional_status_check
      CHECK (refeps_professional_status IS NULL OR refeps_professional_status IN ('validated', 'not_found', 'inactive', 'unavailable'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_refeps_validation_mode_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_refeps_validation_mode_check
      CHECK (refeps_validation_mode IS NULL OR refeps_validation_mode IN ('official', 'sandbox', 'unavailable'));
  END IF;

  -- Official CUIR (Res. 2214/2025 Anexo IV): 6 numeric modules, no separators, 17..41 digits.
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_cuir_official_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_cuir_official_check CHECK (
      cuir IS NULL OR (cuir ~ '^[0-9]{17,41}$' AND repository_mode = 'external' AND sandbox_reference IS NULL)
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_sandbox_reference_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_sandbox_reference_check CHECK (
      sandbox_reference IS NULL OR (sandbox_reference ~ '^SBX-[A-Z0-9-]{4,60}$' AND repository_mode = 'sandbox' AND cuir IS NULL)
    );
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_cuir_assigned_requires_cuir_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_cuir_assigned_requires_cuir_check
      CHECK (national_rx_state IS DISTINCT FROM 'cuir_assigned' OR cuir IS NOT NULL);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prescription_drafts_national_attempts_check') THEN
    ALTER TABLE public.prescription_drafts ADD CONSTRAINT prescription_drafts_national_attempts_check
      CHECK (national_attempts BETWEEN 0 AND 100);
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_prescription_drafts_national_idempotency
